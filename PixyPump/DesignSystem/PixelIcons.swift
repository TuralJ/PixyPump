/// Turns a glyph into a crisp, tintable image (made once, then reused).
/// Safe to use from anywhere (the cache is guarded by a lock).
nonisolated enum PixelIcons {
    nonisolated(unsafe) private static var cache: [String: UIImage] = [:]
    nonisolated(unsafe) private static let lock = NSLock()

    static func uiImage(_ glyph: PixelGlyph, size: CGFloat) -> UIImage {
        let key = "\(glyph)-\(size)"
        lock.lock()
        let cached = cache[key]
        lock.unlock()
        if let cached { return cached }
        let format = UIGraphicsImageRendererFormat()
        format.scale = 3   // 24-grid pixels land exactly on screen pixels
        let renderer = UIGraphicsImageRenderer(size: CGSize(width: size, height: size), format: format)
        let cell = size / 24
        let image = renderer.image { ctx in
            ctx.cgContext.setShouldAntialias(false)
            UIColor.black.setFill()
            for (y, row) in glyph.rows.enumerated() {
                for x in 0..<24 where (row >> UInt32(23 - x)) & 1 == 1 {
                    ctx.fill(CGRect(x: CGFloat(x) * cell, y: CGFloat(y) * cell, width: cell, height: cell))
                }
            }
        }.withRenderingMode(.alwaysTemplate)
        lock.lock()
        cache[key] = image
        lock.unlock()
        return image
    }
}

extension Image {
    /// A pixel icon. Colour it with `.foregroundStyle(...)`.
    /// Sizes that are multiples of 8 (16, 24, 32, 48) look sharpest.
    nonisolated static func pixel(_ glyph: PixelGlyph, size: CGFloat = 24) -> Image {
        let ui = PixelIcons.uiImage(glyph, size: size)
        // Decorative: VoiceOver reads the button/label text instead of "image".
        if let cg = ui.cgImage {
            return Image(decorative: cg, scale: ui.scale).renderingMode(.template)
        }
        return Image(uiImage: ui).renderingMode(.template)
    }

    /// Tab bar version (the tab bar needs a UIImage-backed icon).
    nonisolated static func pixelTab(_ glyph: PixelGlyph) -> Image {
        Image(uiImage: PixelIcons.uiImage(glyph, size: 24)).renderingMode(.template)
    }
}

